export type KategoriTemplate =
  "dokumen" | "presentasi" | "spreadsheet" | "infografis";

export interface TemplateGaleri {
  id: string;
  nama: string;
  kategori: KategoriTemplate;
  format: "word" | "pptx" | "xlsx" | "diagram" | "pdf";
  deskripsi: string;
  ikon: string;
  judulDokumen: string;
  blocks: ContentBlock[];
  versi?: string;
  bagianPRD?: string;
}

