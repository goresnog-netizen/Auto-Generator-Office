export type BlockTanpaId =
  | Omit<HeadingBlock, "id">
  | Omit<ParagraphBlock, "id">
  | Omit<ListBlock, "id">
  | Omit<TableBlock, "id">
  | Omit<CodeBlock, "id">
  | Omit<ImageBlock, "id">
  | Omit<ChartBlock, "id">
  | Omit<DiagramBlock, "id">
  | Omit<DividerBlock, "id">;

export const b = (id: string, block: BlockTanpaId & { id?: string }) =>
  ({ ...block, id }) as ContentBlock;

